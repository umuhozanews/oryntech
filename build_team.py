"""Render the "Our Team" section onto the About page from team.json.

The roster lives in team.json so the page markup never has to be hand-edited.
Re-running replaces the previously injected section, so this is safe to run
every time the roster changes.

Only utility classes that exist in the compiled bundle (or in
assets/utilities.css) are used here - hand-invented Tailwind classes have no
rules behind them on this site and silently do nothing.
"""
import html
import json
import os
import re
import sys

sys.stdout.reconfigure(encoding="utf-8", errors="replace")

ROSTER = "team.json"
# Both files are copies of the same route and must stay identical.
TARGETS = ["en/inside-oryntech.html", "en/inside-oryntech/index.html"]

START = "<!-- 3b. Our Team (generated by build_team.py) -->"
END = "<!-- /Our Team -->"

# Insert directly after the "What Drives Us" section, as requested.
ANCHOR = "<!-- 4. Our Approach -->"


def initials(name):
    parts = [p for p in re.split(r"\s+", name.strip()) if p]
    return (parts[0][:1] + (parts[-1][:1] if len(parts) > 1 else "")).upper()


def card(member):
    name = html.escape(member["name"])
    title = html.escape(member["title"])
    bio = html.escape(member.get("bio", ""))
    photo = member.get("photo")
    linkedin = member.get("linkedin")

    if photo:
        # alt="" because the name sits in the heading right beneath it; a
        # repeated name would just be read out twice.
        media = (f'<img alt="" class="w-full aspect-square rounded-xl object-cover mb-5" '
                 f'decoding="async" height="400" loading="lazy" src="{html.escape(photo)}" '
                 f'width="400"/>')
    else:
        media = ('<div aria-hidden="true" class="w-16 aspect-square rounded-full bg-blue-50 '
                 'text-creiden-blue inline-flex items-center justify-center font-bold mb-5">'
                 f'{html.escape(initials(member["name"]))}</div>')

    link = ""
    if linkedin:
        link = (f'\n<a class="text-[13px] font-bold text-creiden-blue mt-4 inline-flex" '
                f'href="{html.escape(linkedin)}" rel="noopener noreferrer" target="_blank">'
                f'LinkedIn<span class="sr-only"> profile for {name}</span></a>')

    return (
        '<li class="p-6 rounded-2xl bg-white border border-gray-200 hover:border-gray-300 transition">\n'
        f'{media}\n'
        f'<h3 class="text-[18px] font-bold text-creiden-charcoal mb-2">{name}</h3>\n'
        '<div class="text-[12px] font-bold tracking-[0.12em] uppercase text-creiden-blue mb-2">'
        f'{title}</div>\n'
        f'<p class="text-[14.5px] leading-relaxed text-gray-600 m-0">{bio}</p>{link}\n'
        '</li>'
    )


def section(data):
    cards = "\n".join(card(m) for m in data["members"])
    return f"""{START}
<section aria-labelledby="team-heading" class="relative bg-white py-20 min-[1024px]:py-28 border-y border-gray-100">
<div class="mx-auto max-w-[var(--container-lg-2)] px-4 min-[480px]:px-6 min-[768px]:px-8 min-[900px]:px-10">
<div class="max-w-3xl mb-16">
<div class="text-[12px] font-bold tracking-[0.12em] uppercase text-creiden-blue mb-3">{html.escape(data['eyebrow'])}</div>
<h2 class="text-[clamp(30px,4vw,44px)] font-bold tracking-tight text-creiden-charcoal leading-[1.25]" id="team-heading">
            {html.escape(data['heading'])}
          </h2>
<p class="mt-4 text-[17px] leading-relaxed text-fg-2">
            {html.escape(data['intro'])}
          </p>
</div>
<ul class="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-6 list-none p-0 m-0">
{cards}
</ul>
</div>
</section>
{END}
"""


def main():
    data = json.load(open(ROSTER, encoding="utf-8"))
    members = data.get("members", [])

    for path in TARGETS:
        if not os.path.exists(path):
            print(f"  skip (missing): {path}")
            continue
        text = open(path, encoding="utf-8", errors="ignore").read()

        # Drop any previously generated section before inserting the new one.
        text, removed = re.subn(re.escape(START) + r".*?" + re.escape(END) + r"\n?",
                                "", text, flags=re.S)

        if members:
            if ANCHOR not in text:
                print(f"  !! anchor not found in {path}")
                continue
            text = text.replace(ANCHOR, section(data) + ANCHOR, 1)

        open(path, "w", encoding="utf-8", errors="ignore").write(text)
        state = "replaced" if removed else "inserted"
        print(f"  {state if members else 'removed'}: {path}")

    if not members:
        print("\nteam.json has no members, so no section was written.")
        print("Add entries shaped like:")
        print('  {"name": "...", "title": "...", "bio": "...",')
        print('   "photo": "/assets/oryntech/team/<file>", "linkedin": "https://..."}')
    else:
        print(f"\n{len(members)} member(s) rendered")


if __name__ == "__main__":
    main()
