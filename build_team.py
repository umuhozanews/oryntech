def main():
    data = json.load(open(ROSTER, encoding="utf-8"))
    members = data.get("members", [])

    for path in TARGETS:
        if not os.path.exists(path):
            print(f"  skip (missing): {path}")
            continue
        text = open(path, encoding="utf-8", errors="ignore").read()

        # Drop any previously generated sections before inserting
        text, _ = re.subn(re.escape(START_TEAM) + r".*?" + re.escape(END_TEAM) + r"\n?", "", text, flags=re.S)
        text, _ = re.subn(re.escape(START_CULTURE) + r".*?" + re.escape(END_CULTURE) + r"\n?", "", text, flags=re.S)

        # 1. Insert Team Roster before "<!-- 4. Our Approach -->"
        if members:
            if ANCHOR_TEAM in text:
                text = text.replace(ANCHOR_TEAM, team_section(data) + ANCHOR_TEAM, 1)
            else:
                print(f"  !! {ANCHOR_TEAM} not found in {path}")

        # 2. Insert Culture section before "</main>"
        if ANCHOR_CULTURE in text:
            text = text.replace(ANCHOR_CULTURE, culture_section() + ANCHOR_CULTURE, 1)
        else:
            print(f"  !! {ANCHOR_CULTURE} not found in {path}")

        open(path, "w", encoding="utf-8", errors="ignore").write(text)
        print(f"  updated: {path}")

    print(f"\nRendered {len(members)} team member(s) and {len(CULTURE_PHOTOS)} culture gallery photo(s) across {len(TARGETS)} pages.")


if __name__ == "__main__":
    main()
