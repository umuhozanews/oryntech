def initials(name):
    parts = [p for p in re.split(r"\s+", name.strip()) if p]
    return (parts[0][:1] + (parts[-1][:1] if len(parts) > 1 else "")).upper()


def card(member):
    name = html.escape(member["name"])
    title = html.escape(member["title"])
    bio = html.escape(member.get("bio", ""))
    photo = member.get("photo")
    linkedin = member.get("linkedin")

    if photo:
        media = (f'<div class="relative w-full aspect-square overflow-hidden rounded-xl bg-gray-100 mb-5" style="aspect-ratio:1/1;">'
                 f'<img alt="{name}" class="w-full h-full object-cover object-top" '
                 f'decoding="async" height="400" src="{html.escape(photo)}" '
                 f'style="aspect-ratio:1/1;object-position:top center;" width="400"/>'
                 f'</div>')
    else:
        media = ('<div aria-hidden="true" class="w-16 aspect-square rounded-full bg-blue-50 '
                 'text-creiden-blue inline-flex items-center justify-center font-bold mb-5" style="aspect-ratio:1/1;">'
                 f'{html.escape(initials(member["name"]))}</div>')

    link = ""
    if linkedin:
        link = (f'\n<a class="text-[13px] font-bold text-creiden-blue mt-4 inline-flex items-center gap-1.5" '
                f'href="{html.escape(linkedin)}" rel="noopener noreferrer" target="_blank">'
                f'LinkedIn<span class="sr-only"> profile for {name}</span>'
                f'<svg class="w-3.5 h-3.5" fill="none" stroke="currentColor" viewBox="0 0 24 24"><path d="M7 17L17 7M17 7H7M17 7V17" stroke-linecap="round" stroke-linejoin="round" stroke-width="2"/></svg></a>')

    return (
        '<li class="p-6 rounded-2xl bg-white border border-gray-200 hover:border-gray-300 hover:shadow-[0_12px_28px_rgba(54,69,79,0.1)] transition-all duration-300 flex flex-col justify-between hover:-translate-y-1">\n'
        f'<div>\n{media}\n'
        f'<h3 class="text-[18px] font-bold text-creiden-charcoal mb-1">{name}</h3>\n'
        f'<div class="text-[12px] font-bold tracking-[0.12em] uppercase text-creiden-blue mb-3">{title}</div>\n'
        f'<p class="text-[14.5px] leading-relaxed text-gray-600 m-0">{bio}</p>\n'
        f'</div>{link}\n'
        '</li>'
    )


